export function handler(ctx) {
  const { action = 'info', tier = 'VIP' } = ctx;

  if (action === 'courses') {
    const fmt = (k) => {
      const c = COURSES[k];
      return `【${c.title}】\n${c.desc}\n` + c.items.map((i) => `· ${i}`).join('\n');
    };
    return (
      `📚 企业家学院 · 三大课程体系\n\n` +
      fmt('basic') + '\n\n' +
      fmt('senior') + '\n\n' +
      fmt('practice')
    );
  }

  if (action === 'position') {
    return (
      `🎓 企业家学院 · 板块定位\n${board.position}\n\n` +
      `五位一体赋能体系：课程学习 + 标杆参访 + 私董问诊 + 资源对接 + 落地陪跑`
    );
  }

  if (action === 'activities') {
    return (
      `📅 学院常态化活动机制\n` +
      ACTIVITIES.map((a) => `· ${a}`).join('\n')
    );
  }

  if (action === 'advantage') {
    return (
      `✨ 教学赋能特色优势\n` +
      ADVANTAGES.map((a) => `· ${a}`).join('\n')
    );
  }

  // info：权益
  const right = tier === 'SVIP' ? board.svip : board.vip;
  return (
    `🎓 企业家学院\n定位：${board.position}\n` +
    `您的权益（${tier}）：${right}\n` +
    `出勤要求：选定本板块后活动不得无故缺席。`
  );
}
